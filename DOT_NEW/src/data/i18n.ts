export const translate = (
  key: keyof typeof i18n.en,
  language: 'en' | 'ta',
  vars?: Record<string, string | number>,
): string => {
  const text = i18n[language][key as keyof typeof i18n[typeof language]] || i18n.en[key] || key

  if (vars) {
    let result = text as string
    Object.entries(vars).forEach(([varKey, varValue]) => {
      result = result.replace(`{{${varKey}}}`, String(varValue))
    })
    return result
  }

  return text as string
}

